/** A 24 dp icon on Phosphor's 256-unit grid, filled with black so `Icon`'s tint recolours it. */
private fun phosphor(name: String, paths: List<String>, autoMirror: Boolean = false): ImageVector =
    ImageVector.Builder(
        name = "FableIcons.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 256f,
        viewportHeight = 256f,
        autoMirror = autoMirror,
    ).apply {
        paths.forEach { data -> addPath(pathData = addPathNodes(data), fill = SolidColor(Color.Black)) }
    }.build()
